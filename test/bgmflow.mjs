// BGM の流れの検査：任務を通しで進め、いつ・どの区間が鳴り始めたかを記録する。node test/bgmflow.mjs [?synth]
import puppeteer from 'puppeteer';
const q=process.argv[2]||'';
const b=await puppeteer.launch({headless:'new',args:['--use-angle=metal','--enable-gpu','--ignore-gpu-blocklist','--autoplay-policy=no-user-gesture-required']});
const p=await b.newPage();const errs=[];p.on('pageerror',e=>errs.push('PAGEERR '+e.message));p.on('console',m=>{if(/BGM/.test(m.text()))errs.push(m.text());});
await p.goto('http://127.0.0.1:8795/index.html'+q);await p.waitForFunction('window.__SR');
const wait=ms=>new Promise(r=>setTimeout(r,ms));
await p.mouse.click(640,60);await wait(2500);
await p.evaluate(()=>{window.LOG=[];const o=BGM.node;BGM.node=function(g,t,off,dur,fin,fout){LOG.push({ev:'node',at:+AU.ctx.currentTime.toFixed(2),t:+t.toFixed(2),off:+off.toFixed(2),dur:+dur.toFixed(2)});return o.apply(this,arguments);};
  const sm=setMood;window.setMood=function(m){LOG.push({ev:'mood',at:AU.ctx?+AU.ctx.currentTime.toFixed(2):0,m,mode:__SR.G.mode,phase:__SR.G.phase});return sm(m);};});
const st=()=>p.evaluate(()=>({t:+AU.ctx.currentTime.toFixed(1),mood:BGM.mood,cue:BGM.cur?Object.keys(CUES).filter(k=>CUES[k]===BGM.cur.c).join('/'):null,chain:BGM.cur&&BGM.cur.chain,synth:MUS.mood,mode:__SR.G.mode,ph:__SR.G.phase}));
const step=async(name,fn,ms)=>{await p.evaluate(fn);await wait(ms);console.log(name.padEnd(26),JSON.stringify(await st()));};
console.log('開始'.padEnd(26),JSON.stringify(await st()));
await step('出撃カット 2 秒',()=>document.getElementById('bStart').click(),2000);
await step('カットを飛ばす',()=>__SR.skipCut(),1500);
await step('レインバンド',()=>__SR.startRun('bands'),1500);
await step('壁雲',()=>__SR.startRun('wall'),1500);
await step('目',()=>__SR.startRun('eye'),1500);
await step('再攻撃',()=>__SR.startRun('spare'),1500);
await step('発射カット（成功）',()=>{const S=__SR;S.G.spareGiven=true;S.P.hasPod=true;S.startCut(S.CUTS.CUT_FIRE2);},9000);
await step('　…消滅の曲の途中',()=>{},5000);
await step('　…消滅の曲のあと',()=>{},8000);
await step('帰投の局面',()=>{__SR.endCut();},2500);
await step('着陸カット',()=>{const S=__SR;S.startCut(S.CUTS.CUT_LAND);},2500);
await step('一時停止→再開',()=>{},100);
await step('ゲームオーバー→再挑戦(目)',()=>{__SR.endCut&&0;__SR.startRun('eye');},1500);
await step('タイトルへ',()=>__SR.showTitle(),1800);
const log=await p.evaluate(()=>LOG);
console.log('\n鳴り始めた区間（時刻・曲の中の位置）:');for(const l of log)console.log('  '+(l.ev==='mood'?`[${l.at}] setMood(${l.m})  ${l.mode}/${l.phase}`:`[${l.at}] 予約 t=${l.t}  曲 ${l.off}s から ${l.dur}s`));
const vic=log.filter(l=>l.ev==='node'&&Math.abs(l.off-198.67)<1).length;console.log('\n消滅の曲が鳴った回数: '+vic+(vic===1?'（正常）':'（異常）'));
if(errs.length)console.log(errs.join('\n'));await b.close();
